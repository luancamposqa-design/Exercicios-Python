print("2. Separar tudo antes de começar: fralda limpa, lenços umedecidos ou algodão com água morna, pomada para assaduras (se necessário), uma sacola para a fralda suja e uma muda de roupa, se precisar.")
print("3. Colocar o bebê deitado de costas em um trocador firme e plano, de preferência com uma toalha ou manta limpa por baixo.")
print("4. Manter uma das mãos sempre sobre o bebê, para ele não rolar nem cair. Nunca deixar o bebê sozinho no trocador.")
print("5. Abrir as fitas adesivas da fralda suja.")
print("6. Levantar as pernas do bebê com uma das mãos, segurando pelos tornozelos.")
print("7. Limpar o bumbum e a região genital com lenços umedecidos, sempre da frente para trás, para não levar sujeira para a região genital, principalmente em meninas.")
print("8. Dobrar a fralda suja ao meio, com a parte suja para dentro, e retirar de baixo do bebê.")
print("9. Colocar a fralda suja na sacola.")
print("10. Secar a pele do bebê com um pano limpo ou deixar secar ao ar por alguns segundos.")
print("11. Passar a pomada para assaduras, se necessário.")
print("12. Colocar a fralda limpa embaixo do bebê, com a parte das fitas na altura da cintura.")
print("13. Puxar a parte da frente da fralda entre as pernas, até a barriga.")
print("14. Fechar as fitas dos dois lados, sem apertar demais, deixando um dedo de folga.")
print("15. Vestir o bebê novamente.")
print("16. Colocar o bebê em um local seguro, como o berço ou no colo.")
print("17. Fechar a sacola e jogar no lixo.")
print("18. Lavar as mãos com água e sabão novamente.")
